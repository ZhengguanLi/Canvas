import AppKit
import XCTest
@testable import ProjectCanvas

final class ClipboardHistoryTests: XCTestCase {
    @MainActor func testImagesCreateThumbnailsDeduplicateAndClearIndependently() throws {
        let bitmap = try XCTUnwrap(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 4, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        let pixels = try XCTUnwrap(bitmap.bitmapData)
        for index in 0..<(bitmap.bytesPerRow * bitmap.pixelsHigh) { pixels[index] = 255 }
        let data = try XCTUnwrap(bitmap.representation(using: .png, properties: [:]))
        let image = try XCTUnwrap(ClipboardHistory.prepareImage(data))
        let history = ClipboardHistory(limit: 1)
        history.receiveImage(image, type: .png)
        let id = try XCTUnwrap(history.images.first?.id)
        history.receiveImage(image, type: .png)
        XCTAssertEqual(history.images.count, 1)
        XCTAssertEqual(history.images.first?.id, id)
        XCTAssertEqual(history.images.first?.data, data)
        XCTAssertGreaterThan(try XCTUnwrap(history.images.first).thumbnail.size.width, 0)
        history.receiveText("keep text")
        history.clearImages()
        XCTAssertTrue(history.images.isEmpty)
        XCTAssertEqual(history.texts.count, 1)
        history.isPaused = true
        history.receiveImage(image, type: .png)
        XCTAssertTrue(history.images.isEmpty)
    }

    @MainActor func testTextDeduplicatesAndRetainsNewestWithinLimit() {
        let history = ClipboardHistory(limit: 2)
        history.receiveText("one")
        history.receiveText("two")
        history.receiveText("one")
        XCTAssertEqual(history.texts.map(\.text), ["one", "two"])
        history.receiveText("three")
        XCTAssertEqual(history.texts.map(\.text), ["three", "one"])
        history.removeText(history.texts[0].id)
        XCTAssertEqual(history.texts.map(\.text), ["one"])
        history.clearTexts()
        XCTAssertTrue(history.texts.isEmpty)
    }

    func testPrivateAndFilePayloadsExcludedForBothCategories() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "public.file-url"] {
            XCTAssertEqual(ClipboardHistory.kind(for: ["public.utf8-plain-text", marker]), .ignored)
            XCTAssertEqual(ClipboardHistory.kind(for: ["public.png", marker]), .ignored)
        }
        XCTAssertEqual(ClipboardHistory.kind(for: ["public.utf8-plain-text", "public.png"]), .text)
        XCTAssertEqual(ClipboardHistory.kind(for: ["public.png"]), .image)
        XCTAssertEqual(ClipboardHistory.kind(for: ["unsupported"]), .ignored)
    }

    @MainActor func testEmptyOversizeAndPausedTextDoNotEnterHistory() {
        let history = ClipboardHistory()
        history.receiveText(" \n ")
        history.receiveText(String(repeating: "a", count: ClipboardHistory.maximumTextBytes + 1))
        XCTAssertTrue(history.texts.isEmpty)
        history.isPaused = true
        history.receiveText("paused")
        XCTAssertTrue(history.texts.isEmpty)
        history.isPaused = false
        history.receiveText("normal")
        XCTAssertEqual(history.texts.first?.text, "normal")
    }

    func testInvalidImageIsRejectedBeforePresentation() {
        XCTAssertNil(ClipboardHistory.prepareImage(Data("not an image".utf8)))
        XCTAssertNil(ClipboardHistory.prepareImage(Data(repeating: 0, count: ClipboardHistory.maximumImageBytes + 1)))
    }
}
